// The per-crew share image's fixed parts (README, Site, Share image). Run by hand when the art changes:
//
//   node scripts/og/build.mjs
//
// 1. public/og/bg.jpg: the frame behind the text, 1200x630. The fight from public/screenshot.jpg (the
//    same frame as og.jpg) sits on the right with the HUD cropped off, and the left is darkened so the
//    crew's name reads on a plain dark ground.
// 2. worker/og-metrics.ts: each character's advance in Bungee and Teko SemiBold (per 1000 units of font
//    size), from the same TTFs the Worker renders with. resvg draws text but can't tell the Worker how
//    wide it came out, so the layout (worker/og.ts) fits the name with this table.
import { createCanvas, loadImage, GlobalFonts } from '@napi-rs/canvas';
import fs from 'node:fs';

const root = new URL('../../', import.meta.url);
const W = 1200, H = 630;

const shot = await loadImage(fs.readFileSync(new URL('public/screenshot.jpg', root)));
const c = createCanvas(W, H), g = c.getContext('2d');
g.fillStyle = '#07020f'; g.fillRect(0, 0, W, H);
// source rows 96-680 (the HUD above and the sound prompt below cut off), scaled to the full height and
// shifted right so the two fighters land at about x 830-1130
const sy = 96, sh = 584, k = H / sh, dx = 270;
g.drawImage(shot, 0, sy, 1280, sh, dx, 0, 1280 * k, H);
// the dark ground for the text: opaque to x 420 (past the frame's left edge), then fading out by x 860
// (a legibility scrim, not decoration)
const scrim = g.createLinearGradient(0, 0, 860, 0);
scrim.addColorStop(0, 'rgba(7,2,15,1)'); scrim.addColorStop(420 / 860, 'rgba(7,2,15,1)'); scrim.addColorStop(620 / 860, 'rgba(7,2,15,0.85)'); scrim.addColorStop(1, 'rgba(7,2,15,0)');
g.fillStyle = scrim; g.fillRect(0, 0, 860, H);
fs.writeFileSync(new URL('public/og/bg.jpg', root), c.toBuffer('image/jpeg', 82));

const faces = { bungee: 'public/og/bungee-latin.ttf', teko: 'public/og/teko-600-latin.ttf' };
const out = {};
for (const [k, file] of Object.entries(faces)) {
  const fam = 'OG' + k;
  GlobalFonts.registerFromPath(new URL(file, root).pathname, fam);
  const m = createCanvas(10, 10).getContext('2d');
  m.font = `1000px ${fam}`;
  const adv = {};
  for (let cp = 0x20; cp <= 0x7e; cp++) adv[String.fromCharCode(cp)] = Math.round(m.measureText(String.fromCharCode(cp)).width);
  adv['·'] = Math.round(m.measureText('·').width);
  out[k] = adv;
}
fs.writeFileSync(new URL('worker/og-metrics.ts', root),
  `// Generated by scripts/og/build.mjs from public/og/*.ttf: each character's advance per 1000 units of font size.\n` +
  `export const ADVANCE: Record<"bungee" | "teko", Record<string, number>> = ${JSON.stringify(out)};\n`);
console.log('wrote public/og/bg.jpg and worker/og-metrics.ts', out.bungee.M, out.bungee.I, out.teko.M);
